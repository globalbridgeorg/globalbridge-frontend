-- Helper para gerar username único a partir de nome/e-mail
create or replace function private.gerar_username_unico(base_texto text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  limpo text;
  candidato text;
  sufixo int := 1;
begin
  limpo := lower(regexp_replace(coalesce(base_texto, ''), '[^a-zA-Z0-9]+', '-', 'g'));
  limpo := trim(both '-' from limpo);
  if limpo = '' then
    limpo := 'usuario';
  end if;
  limpo := left(limpo, 32);
  candidato := limpo;
  while exists (select 1 from public.profiles where username = candidato) loop
    sufixo := sufixo + 1;
    candidato := limpo || sufixo::text;
  end loop;
  return candidato;
end;
$$;
revoke all on function private.gerar_username_unico(text) from public, anon, authenticated;

-- Trigger automático ao criar conta no Supabase Auth
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  nome_inicial text;
  uname text;
begin
  nome_inicial := coalesce(
    nullif(trim(new.raw_user_meta_data->>'name'), ''),
    split_part(coalesce(new.email, 'usuario'), '@', 1)
  );
  uname := private.gerar_username_unico(nome_inicial);
  insert into public.profiles (id, auth_user_id, username, name, tipo)
  values (new.id, new.id, uname, nome_inicial, 'estudante')
  on conflict (id) do nothing;
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- Impede usuário comum de alterar tipo/auth_user_id no próprio perfil
create or replace function private.guard_profile_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if current_user not in ('postgres', 'service_role') and not private.is_admin() then
    if new.tipo is distinct from old.tipo then
      raise exception 'Não é permitido alterar o tipo de conta diretamente.' using errcode = '42501';
    end if;
    if new.auth_user_id is distinct from old.auth_user_id then
      raise exception 'Não é permitido alterar o vínculo de autenticação.' using errcode = '42501';
    end if;
  end if;
  return new;
end;
$$;
revoke all on function private.guard_profile_update() from public, anon, authenticated;

create trigger trg_guard_profile_update
  before update on public.profiles
  for each row execute function private.guard_profile_update();


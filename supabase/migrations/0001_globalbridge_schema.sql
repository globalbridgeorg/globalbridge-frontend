-- Validador de URL contra esquemas maliciosos (javascript:, data:, vbscript:)
create or replace function private.url_segura(u text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select u is null
    or trim(u) = ''
    or trim(u) ~* '^https?://'
    or trim(u) !~* '^[a-z][a-z0-9+.-]*:';
$$;
revoke all on function private.url_segura(text) from public, anon, authenticated;

-- Protege colunas sensíveis de agencias contra alteração direta e bloqueia XSS em URLs
create or replace function private.guard_agencia_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  url_item text;
begin
  if current_user not in ('postgres', 'service_role') and not private.is_admin() then
    if new.ativo is distinct from old.ativo
      or new.usuario_id is distinct from old.usuario_id
      or new.data_cadastro is distinct from old.data_cadastro
      or new.estado_id is distinct from old.estado_id
    then
      raise exception 'Você não tem permissão para alterar campos administrativos da agência.' using errcode = '42501';
    end if;
  end if;

  if not private.url_segura(new.site) then
    raise exception 'URL do site inválida.' using errcode = '22023';
  end if;

  for url_item in
    select v from (values
      (new.conteudo_blocos #>> '{video,url}'),
      (new.conteudo_blocos #>> '{localizacao,link_mapa}'),
      (new.conteudo_blocos #>> '{redes_sociais,instagram}'),
      (new.conteudo_blocos #>> '{redes_sociais,facebook}'),
      (new.conteudo_blocos #>> '{redes_sociais,tiktok}'),
      (new.conteudo_blocos #>> '{redes_sociais,linkedin}'),
      (new.conteudo_blocos #>> '{redes_sociais,youtube}')
    ) as t(v)
  loop
    if not private.url_segura(url_item) then
      raise exception 'URL inválida nos blocos da página.' using errcode = '22023';
    end if;
  end loop;

  return new;
end;
$$;
revoke all on function private.guard_agencia_update() from public, anon, authenticated;

